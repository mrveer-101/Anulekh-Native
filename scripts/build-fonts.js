// Generates src/vector-fonts-b64.css: the icon fonts the app uses, embedded as base64.
// Embedding keeps icons working on static web hosts that don't serve files from node_modules paths.
// Font files and family names come straight from @expo/vector-icons, so glyphs always match its glyph maps.
// Re-run after upgrading @expo/vector-icons:  npm run build:fonts
const fs = require('fs');
const path = require('path');

const FONT_DIR = path.join(__dirname, '../node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts');
const OUTPUT = path.join(__dirname, '../src/vector-fonts-b64.css');

// [font-family registered by @expo/vector-icons, font file]
const FONTS = [
  ['feather', 'Feather.ttf'],
  ['ionicons', 'Ionicons.ttf'],
  ['FontAwesome5Free-Solid', 'FontAwesome5_Solid.ttf'],
  ['FontAwesome5Free-Regular', 'FontAwesome5_Regular.ttf'],
  ['FontAwesome5Free-Brand', 'FontAwesome5_Brands.ttf'],
];

const css = FONTS.map(([family, file]) => {
  const base64 = fs.readFileSync(path.join(FONT_DIR, file)).toString('base64');
  return `@font-face {
  font-family: '${family}';
  src: url('data:font/truetype;charset=utf-8;base64,${base64}') format('truetype');
  font-weight: normal;
  font-style: normal;
}
`;
}).join('');

fs.writeFileSync(OUTPUT, `/* Generated by scripts/build-fonts.js — do not edit by hand. */\n${css}`);
console.log(`Wrote ${FONTS.length} icon fonts to ${path.relative(process.cwd(), OUTPUT)}`);
